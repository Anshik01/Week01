public class AveragePercent{
	public static void main(String[]args){
		
		double mathMark = 94.0;
		double physicsMark = 95.0;
		double chemistryMark = 96.0;
		
		double averagePercent = (mathMark + physicsMark + chemistryMark) / 300.0 * 100.0;
		System.out.println("Sam's average mark in PCM is " + averagePercent);
	}
}	
